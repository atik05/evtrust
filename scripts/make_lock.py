"""Turn the package list recorded by a run into requirements-lock.txt.

    python scripts/make_lock.py runs/acn/software_versions.txt > requirements-lock.txt

The pipeline records `pip freeze` for every run. This keeps the pinned packages and drops lines that
only make sense on the machine that produced them: the editable install of evtrust itself, local paths
and VCS references.
"""
import sys
from pathlib import Path

src = Path(sys.argv[1])
keep, dropped = [], []
for line in src.read_text().splitlines():
    s = line.strip()
    if not s or s.startswith('#'):
        continue
    local = s.startswith(('-e ', '--editable')) or ' @ file:' in s or ' @ git+' in s or s.lower().startswith('evtrust')
    (dropped if local else keep).append(s)
print(f'# Exact package versions of the run recorded in {src.name}. Generated by scripts/make_lock.py.')
print('\n'.join(sorted(keep, key=str.lower)))
print(f'kept {len(keep)} pinned packages, dropped {len(dropped)} machine-specific lines', file=sys.stderr)
