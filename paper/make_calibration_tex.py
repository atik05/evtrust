"""Calibration over time: the sentence in Results and the Supplementary table.

    python make_calibration_tex.py data/calibration_robustness_acn.csv [data/calibration_robustness_paloalto.csv]

Each CSV is written by scripts/calibration_robustness.py. Writes calibrationnumbers.tex (macro \\CalibrationSentence)
and si_calibration.tex. Networks are reported in the order given; a network whose file is absent is left out, so the
sentence never carries a placeholder.
"""
import sys
from pathlib import Path

import pandas as pd

NAMES = {'ACN': 'ACN', 'PaloAlto': 'Palo Alto', 'Palo Alto': 'Palo Alto'}
SETTING = {'A': 'Driver seen', 'C': 'Unseen, history', 'D': 'Cold start'}
LEARNER = {'catboost': 'CatBoost', 'ft': 'FT-Transformer'}
CAL = {'all periods (main analysis)': 'all', 'prospective': 'pro'}


def num(x: float, nd: int = 1) -> str:
    s = f'{x:.{nd}f}'
    if s.lstrip('-').strip('0.') == '':
        s = s.lstrip('-')
    return s.replace('-', '$-$') if s.startswith('-') else s


def summarise(f: Path) -> pd.DataFrame:
    r = pd.read_csv(f)
    r['cal'] = r['calibration'].map(CAL)
    return r.groupby(['network', 'learner', 'setting', 'cal'])[['flex_at_1pct', 'flex_at_2pct', 'flex_at_5pct', 'sessions_scored']].mean().reset_index()


def main(files):
    tabs = [summarise(Path(f)) for f in files if Path(f).exists()]
    if not tabs:
        raise SystemExit('no calibration-robustness file found')
    t = pd.concat(tabs)
    order = list(dict.fromkeys(t['network']))

    # sentence (CatBoost, as in the main text); every claim is computed, so it holds for whichever networks are present
    parts = []
    for n in order:
        c = t[(t['network'] == n) & (t['learner'] == 'catboost')].set_index(['setting', 'cal'])['flex_at_2pct']
        change = max(abs(c[(s, 'pro')] - c[(s, 'all')]) for s in SETTING)
        loss = {k: 100 * (1 - c[('D', k)] / c[('C', k)]) for k in ('all', 'pro')}
        parts.append((NAMES.get(n, n), change, loss))
    maxchange = max(p[1] for p in parts)
    floor_loss = min(min(p[2].values()) for p in parts)
    losses = '; '.join(f"{name}: {num(l['pro'])}\\,\\% against {num(l['all'])}\\,\\%" for name, _, l in parts)
    spread = max(abs(p[2]['pro'] - p[2]['all']) for p in parts)
    verdict = ('leaves the loss at a cold start essentially unchanged' if spread < 1.5 else
               f'changes the loss at a cold start by up to {num(spread)} percentage points, so that a cold start still removes at least {int(floor_loss)}\\,\\% of the flexibility')
    sentence = ('Calibrating the shifts only on residuals of sessions completed before the month of each arrival, as an '
                f'operator could, changes the flexibility retained at 2\\,\\% undelivered energy by at most {num(maxchange)} '
                f'percentage points and {verdict} (on the sessions both versions can score, {losses} with residuals '
                'from all periods; Supplementary Table \\siref{tab:s-calibration}).')
    Path('calibrationnumbers.tex').write_text('% generated by make_calibration_tex.py\n'
                                             f'\\newcommand{{\\CalibrationSentence}}{{{sentence}}}\n')

    # Supplementary table
    lines = ['\\section{Calibration over time}\\label{sec:s-calibration}',
             'The smart-charging analysis shifts each forecast by quantiles of the residuals of the other driver groups from '
             'all periods. This section repeats it with quantiles computed only from residuals of other driver groups whose '
             'sessions ended before the month of the session\'s arrival. Both are scored on the same sessions, those with at '
             'least 200 such residuals.',
             '\\begin{table}[htbp]\\centering\\footnotesize',
             '\\caption{Flexibility retained (\\% of oracle) at undelivered-energy shares of 1, 2 and 5\\,\\%, with quantiles '
             'from all periods (as in the main text) and from earlier sessions only, mean over five seeds.}\\label{tab:s-calibration}',
             '\\begin{tabular}{lllrrrrrr}', '\\toprule',
             ' & & & \\multicolumn{3}{c}{All periods} & \\multicolumn{3}{c}{Earlier sessions only} \\\\',
             '\\cmidrule(lr){4-6}\\cmidrule(lr){7-9}',
             'Network & Learner & Forecast & 1\\% & 2\\% & 5\\% & 1\\% & 2\\% & 5\\% \\\\', '\\midrule']
    for n in order:
        for l in ('catboost', 'ft'):
            for s in SETTING:
                g = t[(t['network'] == n) & (t['learner'] == l) & (t['setting'] == s)].set_index('cal')
                if g.empty:
                    continue
                vals = [num(g.loc[k, f'flex_at_{x}pct']) for k in ('all', 'pro') for x in (1, 2, 5)]
                lines.append(f"{NAMES.get(n, n)} & {LEARNER[l]} & {SETTING[s]} & " + ' & '.join(vals) + ' \\\\')
        sess = int(t[t['network'] == n]['sessions_scored'].iloc[0])
        lines.append(f"\\multicolumn{{9}}{{l}}{{\\emph{{{NAMES.get(n, n)}: {sess:,} sessions per seed scored.}}}} \\\\")
        if n != order[-1]:
            lines.append('\\midrule')
    lines += ['\\bottomrule', '\\end{tabular}', '\\end{table}']
    Path('si_calibration.tex').write_text('% generated by make_calibration_tex.py\n' + '\n'.join(lines) + '\n')
    print(sentence)


if __name__ == '__main__':
    main(sys.argv[1:])
